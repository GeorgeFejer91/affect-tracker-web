export function webXrStimulusById(id) {
  return WEBXR_STIMULI.find((stimulus) => stimulus.id === id) ?? WEBXR_STIMULI[0];
}

export function stimulusDurationSeconds(stimulus) {
  if (!stimulus?.frameCount || !stimulus?.frameRate) return undefined;
  return stimulus.frameCount / stimulus.frameRate;
}

export function stimulusFilenameToken(stimulus) {
  return String(stimulus?.id ?? "stimulus").replace(/[^a-z0-9-]+/gi, "-").toLowerCase();
}
